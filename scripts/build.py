def slugify(text: str) -> str:
    s = re.sub(r"[^\w\s-]", "", text.lower()).strip()
    return re.sub(r"[\s_-]+", "-", s) or "post"


def to_date(val, fallback: date) -> date:
    if isinstance(val, datetime):
        return val.date()
    if isinstance(val, date):
        return val
    if isinstance(val, str):
        for fmt in ("%Y-%m-%d", "%d/%m/%Y", "%Y/%m/%d"):
            try:
                return datetime.strptime(val.strip(), fmt).date()
            except ValueError:
                pass
    return fallback


def norm_tags(raw) -> list[str]:
    if isinstance(raw, list):
        items = [str(x) for x in raw]
    elif isinstance(raw, str):
        s = raw.strip().strip("\"'").strip("[]")
        items = re.split(r"[,\s]+", s)
    else:
        items = []
    cleaned = [re.sub(r"^#+", "", x.strip().lower()) for x in items if x.strip()]
    return cleaned or ["security"]


def obsidian_to_md(text: str, slugs: dict[str, str]) -> str:
    text = re.sub(r"%%.*?%%", "", text, flags=re.S)
    text = re.sub(r"!\[\[([^\]]+)\]\]", lambda m: f"![{m.group(1)}]({m.group(1)})", text)

    def repl_link(m):
        inner = m.group(1)
        target, _, label = inner.partition("|")
        label = label or target
        key = slugify(target)
        if key in slugs:
            return f"[{label}](../{slugs[key]}/)"
        return label

    text = re.sub(r"\[\[([^\]]+)\]\]", repl_link, text)
    text = re.sub(r"==([^=\n]+)==", r"<mark>\1</mark>", text)
    return text


def parse_post(path: Path) -> dict | None:
    raw = path.read_text(encoding="utf-8")
    meta = {}
    body = raw
    if raw.startswith("---"):
        parts = raw.split("---", 2)
        if len(parts) == 3:
            try:
                meta = yaml.safe_load(parts[1]) or {}
            except Exception:
                meta = {}
            body = parts[2].lstrip("\r\n")
    if meta.get("draft") is True:
        return None

    fallback_dt = date.fromtimestamp(path.stat().st_mtime)
    title = str(meta.get("title") or path.stem.replace("-", " ").title())
    dt = to_date(meta.get("date"), fallback_dt)
    summary = str(meta.get("summary") or "")
    if not summary:
        for para in body.split("\n\n"):
            p = para.strip()
            if p and not p.startswith("#") and not p.startswith("```"):
                summary = re.sub(r"[*_`#\[\]]", "", p)[:200]
                break
    tags = norm_tags(meta.get("tags"))
    slug = slugify(meta.get("slug") or path.stem)
    return {
        "title": title,
        "date": dt,
        "summary": summary or title,
        "tags": tags,
        "slug": slug,
        "body": body,
    }


def render_tags(tags: list[str], indent: str = "          ") -> str:
    return "\n".join(
        f'{indent}<span class="tag {TAG_CLASS.get(t, "tag")}">{html.escape(t)}</span>'
        for t in tags
    )


def post(meta: dict, year: int, slugs: dict[str, str]) -> str:
    md_text = obsidian_to_md(meta["body"], slugs)
    md = markdown.Markdown(extensions=["fenced_code", "tables", "toc"])
    html_body = md.convert(md_text)

    words = max(1, len(re.findall(r"\w+", meta["body"])))
    read = max(1, round(words / 200))
    url = f"{SITE}/blog/{meta['slug']}/"
    iso_date = meta["date"].isoformat()
    disp_date = meta["date"].strftime("%d/%m/%y")

    toc_items = []
    for token in getattr(md, "toc_tokens", []):
        toc_items.append(f'      <li><a href="#{token["id"]}">{html.escape(token["name"])}</a></li>')
        for child in token.get("children", []):
            toc_items.append(f'      <li style="padding-left:10px;"><a href="#{child["id"]}">&rsaquo; {html.escape(child["name"])}</a></li>')

    jsonld = json.dumps(
        {
            "@context": "https://schema.org",
            "@type": "BlogPosting",
            "headline": meta["title"],
            "description": meta["summary"],
            "datePublished": iso_date,
            "url": url,
            "author": {"@type": "Person", "name": AUTHOR, "sameAs": SAME_AS},
        }
    )

    return PAGE.substitute(
        title=html.escape(meta["title"]),
        summary=html.escape(meta["summary"]),
        url=url,
        author=html.escape(AUTHOR),
        iso_date=iso_date,
        date=disp_date,
        words=words,
        read=read,
        tags=render_tags(meta["tags"], "        "),
        body=html_body,
        toc="\n".join(toc_items) if toc_items else '      <li><a href="#">Top</a></li>',
        slug=meta["slug"],
        jsonld=jsonld,
    )


def card(meta: dict) -> str:
    words = max(1, len(re.findall(r"\w+", meta["body"])))
    read = max(1, round(words / 200))
    return CARD.substitute(
        slug=meta["slug"],
        date=meta["date"].strftime("%d/%m/%y"),
        read=read,
        words=words,
        title=html.escape(meta["title"]),
        summary=html.escape(meta["summary"]),
        tags=render_tags(meta["tags"], "          "),
    )


def build() -> int:
    SRC.mkdir(parents=True, exist_ok=True)
    posts = []
    for p in sorted(SRC.glob("*.md")):
        parsed = parse_post(p)
        if parsed:
            posts.append(parsed)
    posts.sort(key=lambda x: (x["date"], x["slug"]), reverse=True)
    slugs = {slugify(p["title"]): p["slug"] for p in posts}
    slugs.update({p["slug"]: p["slug"] for p in posts})

    year = date.today().year
    for p in posts:
        out_dir = BLOG / p["slug"]
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / "index.html").write_text(post(p, year, slugs), encoding="utf-8")
        print(f"  rendered blog/{p['slug']}/index.html")

    idx_html = INDEX.read_text(encoding="utf-8")
    cards_block = "\n\n".join(card(p) for p in posts)
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    replacement = f"{START}\n\n{cards_block}\n\n    {END}"
    INDEX.write_text(pattern.sub(replacement, idx_html), encoding="utf-8")
    print(f"  blog/index.html ({len(posts)} cards)")

    lastmod = posts[0]["date"].isoformat() if posts else date.today().isoformat()
    urls = [(SITE + "/", lastmod), (SITE + "/blog/", lastmod)]
    urls += [(f"{SITE}/blog/{p['slug']}/", p["date"].isoformat()) for p in posts]
    entries = "\n".join(f"  <url>\n    <loc>{u}</loc>\n    <lastmod>{d}</lastmod>\n  </url>" for u, d in urls)
    (ROOT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{entries}\n</urlset>\n",
        encoding="utf-8",
    )
    print(f"  sitemap.xml ({len(urls)} urls)")
    return 0


def check() -> int:
    meta = {
        "title": "T & <x>",
        "date": date(2026, 1, 2),
        "summary": "s",
        "tags": ["android"],
        "slug": "s",
        "body": "## Head\n\n```python\nprint(1)\n```",
    }
    slugs = {"s": "s"}
    out = post(meta, 2026, slugs)
    assert "T &amp; &lt;x&gt;" in out, "title not escaped"
    assert 'id="head"' in out, "toc ids missing"
    assert "tag-android" in out, "tag class broken"
    assert "02/01/26" in out, "date format broken"
    assert card(meta).count('href="s/"') == 1, "card slug broken"
    assert 'rel="canonical" href="https://vola12do.github.io/blog/s/"' in out, "canonical missing"
    assert '"@type": "BlogPosting"' in out, "json-ld missing"
    print("self-check ok")
    return 0


if __name__ == "__main__":
    sys.exit(check() if "--check" in sys.argv else build())
